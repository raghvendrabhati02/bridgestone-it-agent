class TestOrchestratorConversationFlows:
    """End-to-end conversation flows with mocked AI provider."""

    def _flow(self, category: str, messages: List[str]) -> List[str]:
        """Run a multi-turn conversation and return all response_text values."""
        provider = _make_mock_ai_provider()
        orch = _build_orchestrator(ai_provider=provider)
        session_id = str(uuid.uuid4())
        history: List[dict] = []
        responses: List[str] = []

        for msg in messages:
            req = _make_request(
                session_id=session_id,
                user_message=msg,
                category=category,
                history=list(history),
            )
            result = orch.handle(req)
            history.append({"role": "user", "text": msg})
            history.append({"role": "model", "text": result.response_text})
            responses.append(result.response_text)

        return responses

    def test_vpn_issue_produces_response(self):
        responses = self._flow("VPN", ["My GlobalProtect VPN keeps disconnecting"])
        assert len(responses) == 1
        assert responses[0]  # non-empty

    def test_multi_turn_vpn_flow(self):
        responses = self._flow("VPN", [
            "My VPN is not connecting",
            "I see error 619",
            "I already restarted my laptop",
        ])
        assert len(responses) == 3
        for r in responses:
            assert r  # all non-empty

    def test_outlook_issue_produces_response(self):
        responses = self._flow("OUTLOOK", ["Outlook is crashing when I open it"])
        assert responses[0]

    def test_printer_issue_produces_response(self):
        responses = self._flow("PRINTER", ["My printer shows offline status"])
        assert responses[0]

    def test_sap_login_failure_flow(self):
        responses = self._flow("SAP", ["I cannot log in to SAP, error RFC_ERROR_LOGON_FAILURE"])
        assert responses[0]

    def test_password_issue_flow(self):
        responses = self._flow("PASSWORD_RESET", ["My Windows password has expired"])
        assert responses[0]

    def test_wifi_issue_flow(self):
        responses = self._flow("GUEST_WIFI", ["I cannot connect to BS-Guest Wi-Fi"])
        assert responses[0]

    def test_hardware_issue_flow(self):
        responses = self._flow("DEVICE_HEALTH", ["My laptop fan is very loud and it is slow"])
        assert responses[0]

    def test_browser_issue_flow(self):
        responses = self._flow("BROWSER", ["Edge browser crashes on our internal portal"])
        assert responses[0]

    def test_response_comes_from_ai_provider_chat(self):
        """Response must come from ai_provider.chat(), not from reasoning layer."""
        expected_response = "Can you tell me what error code you see in GlobalProtect?"
