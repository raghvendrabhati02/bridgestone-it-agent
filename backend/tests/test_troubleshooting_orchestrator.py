"""
test_troubleshooting_orchestrator.py
──────────────────────────────────────────────────────────────────────────────
Comprehensive unit tests for the Enterprise Troubleshooting Orchestrator.

Test strategy
--------------
• Zero real LLM calls — ai_provider is always mocked.
• No database connections — state is in-memory.
• No external network dependencies.
• All ReasoningEngine calls use deterministic mock responses.
• Tests validate:
    - Conversation flows (VPN, Outlook, Printer, SAP, Password, Wi-Fi, Hardware)
    - State persistence across turns
    - Step non-repetition
    - Knowledge retrieval ranking
    - DecisionSchema validation and fallback
    - Reasoning producing structured output only (no response text)
    - Final response generated by ai_provider.chat(), not reasoning
    - Resolution detection
    - Escalation with full session context passed to TicketService
    - Strategy selection by domain
    - GENERAL fallback strategy

Usage
------
    python -m pytest tests/test_troubleshooting_orchestrator.py -v
"""

