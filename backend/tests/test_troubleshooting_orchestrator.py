    def _make_engine(self, decision_json=None):
        from app.services.reasoning_service import ReasoningEngine
        provider = _make_mock_ai_provider(decision_json=decision_json)
        return ReasoningEngine(ai_provider=provider, context_builder=self.ctx_builder), provider

    def _make_context(self, category="VPN", turn_count=0, missing_ev=None, attempted=None):
        from app.services.context_builder import ReasoningContext
        sid = str(uuid.uuid4())
        state = self.state_mgr.create(sid, "VPN issue", category)
