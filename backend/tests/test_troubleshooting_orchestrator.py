        orch = _build_orchestrator(ai_provider=provider)
        sid = str(uuid.uuid4())

        orch.handle(_make_request(session_id=sid, user_message="VPN not working"))
        orch.handle(_make_request(session_id=sid, user_message="Still broken"))

        from app.services.troubleshooting_state_service import TroubleshootingStateManager
        # Access state manager through orchestrator's attribute
        state = orch._state_manager.get(sid)
        assert state is not None
        assert state.turn_count == 2

